@pytest.fixture(scope="module", autouse=True)
def q_app():
    return QApplication.instance() or QApplication([])


def _taskbar(edge, thick, dpi):
    tb = MagicMock()
    top = 1080 - thick if edge == E.BOTTOM else 0

    def p(v):
        return int(round(v * dpi))

    tb.hwnd, tb.dpi_scale, tb.height = 4242, dpi, p(thick)
    tb.rect = (0, p(top), p(1920), p(top + thick))
    tb.tasklist_rect = None
    tb.widgets_rect = None
    tb.apps_extent = (p(652), p(top), p(1269), p(top + thick))
    tb.apps_extent_source = "uia"
    tb.widgets_extent = (p(6), p(top), p(158), p(top + thick))
    tb.get_edge_position.return_value = edge
    s = MagicMock()
    s.geometry.return_value = QRect(0, 0, 1920, 1080)
    s.availableGeometry.return_value = QRect(0, thick if edge == E.TOP else 0, 1920, 1080 - thick)
    s.name.return_value = "S"
    tb.get_screen.return_value = s
    tb.get_tray_rect.return_value = (p(1694), p(top), p(1920), p(top + thick))
    return tb


def test_the_case_grid_is_the_160_frozen_cases():
    grid = list(itertools.product(("BOTTOM", "TOP"), (32, 40, 48, 72), (120, 190), (0, 3, 50, 400, -20),
                                  (1.0, 1.5)))
    assert [tuple(r[:5]) for r in GOLDEN] == grid and len(GOLDEN) == 160


@pytest.mark.parametrize("row", GOLDEN, ids=lambda r: "%s-%d-%d-%d-%s" % tuple(r[:5]))
def test_horizontal_position_and_drag_are_unchanged(row):
    edge_name, thick, width, off, dpi = row[:5]
    edge = getattr(E, edge_name)
    tb = _taskbar(edge, thick, dpi)
    h = min(thick, 48)
    calc = PositionCalculator()
    pos = calc.calculate_position(tb, (width, h), {"tray_offset_x": off, "tray_offset_y": 3})
    d1 = calc.constrain_drag_position(QPoint(0, 500), tb, QSize(width, h))
    d2 = calc.constrain_drag_position(QPoint(1900, 0), tb, QSize(width, h))
    assert (pos.x, pos.y, d1.x(), d1.y(), d2.x(), d2.y()) == tuple(row[5:])


@pytest.mark.parametrize("edge", [E.BOTTOM, E.TOP])
def test_horizontal_bars_never_probe_or_watch(edge):
    """No UIA layout probe, no side-bar watcher (and so no WinEvent hook) for a top/bottom bar."""
    tb = _taskbar(edge, 48, 1.0)
    widget = MagicMock()
    widget.width.return_value, widget.height.return_value = 190, 48
    pm = PositionManager(WindowState(config={"tray_offset_x": 0}, widget=widget, taskbar_info=tb))
    with patch.object(taskbar_utils, "request_taskbar_layout_probe") as probe,             patch.object(pm._side_watcher, "attach") as attach:
        assert pm._side_placement_for(tb, 48) is None
    probe.assert_not_called()
    attach.assert_not_called()
